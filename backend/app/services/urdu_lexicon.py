def _parse(raw: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in raw.strip().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        src, _, dst = line.partition(" ")
        out[src.replace("_", " ")] = dst.strip().replace("_", " ")
    return out


LEXICON: dict[str, str] = _parse(_RAW)


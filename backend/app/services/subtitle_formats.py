"""Subtitle document helpers + SRT / VTT / ASS writers.

A "document segment" is a plain dict:
  {id, start, end, text, sourceText, speaker, style (partial override | None),
   words: [{text, start, end, sourceText?, color?}]}
"""
from __future__ import annotations

import math
import re

from ..schemas.style import merged_style
from . import caption_layout as cl
from . import fonts as font_svc

# ------------------------------------------------------------------ helpers


def tokenize(text: str) -> list[str]:
    return [t for t in re.split(r"\s+", (text or "").strip()) if t]


def display_words(seg: dict) -> list[dict]:
    """Words aligned 1:1 with the caption text tokens. If stored word timings don't line up with the
    current text (e.g. user edited text outside the editor), timings are interpolated."""
    tokens = tokenize(seg.get("text", ""))
    words = seg.get("words") or []
    start, end = float(seg["start"]), float(seg["end"])
    if words and len(words) == len(tokens):
        return [
            {**w, "text": tok, "start": float(w["start"]), "end": float(w["end"])}
            for w, tok in zip(words, tokens)
        ]
    if not tokens:
        return []
    total = sum(max(1, len(t)) for t in tokens)
    out, t = [], start
    for tok in tokens:
        d = (end - start) * max(1, len(tok)) / total
        out.append({"text": tok, "start": t, "end": t + d, "color": None})
        t += d
    return out


def _ts(t: float, sep: str = ",") -> str:
    t = max(0.0, t)
    ms = int(round(t * 1000))
    h, ms = divmod(ms, 3600_000)
    m, ms = divmod(ms, 60_000)
    s, ms = divmod(ms, 1000)
    return f"{h:02d}:{m:02d}:{s:02d}{sep}{ms:03d}"


def _split_two_lines(text: str, limit: int = 42) -> str:
    if len(text) <= limit:
        return text
    words = text.split(" ")
    best, best_diff = text, 10**9
    for i in range(1, len(words)):
        a, b = " ".join(words[:i]), " ".join(words[i:])
        diff = abs(len(a) - len(b))
        if diff < best_diff:
            best, best_diff = f"{a}\n{b}", diff
    return best


def to_srt(segments: list[dict]) -> str:
    out = []
    for i, s in enumerate(sorted(segments, key=lambda s: s["start"]), 1):
        text = " ".join(tokenize(s.get("text", "")))
        if not text:
            continue
        out.append(f"{i}\n{_ts(s['start'])} --> {_ts(s['end'])}\n{_split_two_lines(text)}\n")
    return "\n".join(out)


def to_vtt(segments: list[dict]) -> str:
    out = ["WEBVTT", ""]
    for s in sorted(segments, key=lambda s: s["start"]):
        text = " ".join(tokenize(s.get("text", "")))
        if not text:
            continue
        rtl = cl.is_rtl(text)
        out.append(f"{_ts(s['start'], '.')} --> {_ts(s['end'], '.')}" + (" align:center" if rtl else ""))
        out.append(_split_two_lines(text))
        out.append("")
    return "\n".join(out)


# ------------------------------------------------------------------ ASS


def _ass_time(t: float) -> str:
    cs = int(round(max(0.0, t) * 100))
    h, cs = divmod(cs, 360000)
    m, cs = divmod(cs, 6000)
    s, cs = divmod(cs, 100)
    return f"{h:d}:{m:02d}:{s:02d}.{cs:02d}"


def _ass_color(hex_color: str | None, fallback: str = "#FFFFFF") -> str:
    h = (hex_color or fallback).lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    if not re.fullmatch(r"[0-9a-fA-F]{6}", h):
        h = fallback.lstrip("#")
    r, g, b = h[0:2], h[2:4], h[4:6]
    return f"&H{b}{g}{r}&".upper()


def _ass_alpha(opacity: float) -> str:
    a = int(round((1 - max(0.0, min(1.0, float(opacity)))) * 255))
    return f"&H{a:02X}&"


def _escape(text: str) -> str:
    return text.replace("\\", "/").replace("{", "(").replace("}", ")").replace("\n", " ")


def _f(v: float) -> str:
    return f"{v:.2f}".rstrip("0").rstrip(".") if math.isfinite(v) else "0"


def word_active_windows(words: list[dict], seg_end: float) -> list[tuple[float, float]]:
    """A word is 'active' from its start until the next word starts (or the caption ends)."""
    out = []
    for i, w in enumerate(words):
        nxt = words[i + 1]["start"] if i + 1 < len(words) else seg_end
        out.append((w["start"], max(w["start"], min(nxt, seg_end))))
    return out


def build_ass(segments: list[dict], global_style: dict, width: int, height: int) -> str:
    header = [
        "[Script Info]",
        "; Generated by AI Caption Studio",
        "ScriptType: v4.00+",
        f"PlayResX: {width}",
        f"PlayResY: {height}",
        "WrapStyle: 2",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: None",
        "",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, "
        "Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, "
        "MarginR, MarginV, Encoding",
        "Style: Default,Arial,48,&H00FFFFFF,&H00FFFFFF,&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,0,0,5,0,0,0,1",
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    ]
    events: list[str] = []
    for seg in sorted(segments, key=lambda s: s["start"]):
        if seg["end"] <= seg["start"]:
            continue
        style = merged_style(global_style, seg.get("style"))
        words = display_words(seg)
        if not words:
            continue
        events.extend(_segment_events(seg, words, style, width, height))
    return "\n".join(header + events) + "\n"


def _segment_events(seg: dict, words: list[dict], style: dict, W: int, H: int) -> list[str]:
    font = font_svc.get_font(style.get("fontFamily"))
    lay = cl.layout_caption([w["text"] for w in words], style, W, H)
    start, end = float(seg["start"]), float(seg["end"])
    t0, t1 = _ass_time(start), _ass_time(end)
    dur_ms = max(1, int(round((end - start) * 1000)))
    anim_ms = int(round(float(style.get("animationDuration", 0.25)) * 1000))
    anim_ms = min(anim_ms, dur_ms // 2)
    a_in, a_out = style.get("animationIn", "none"), style.get("animationOut", "none")
    slide_off = 0.06 * H

    def anim_tags(x: float, y: float) -> str:
        tags = ""
        fin = anim_ms if a_in == "fade" else 0
        fout = anim_ms if a_out == "fade" else 0
        if fin or fout:
            tags += f"\\fad({fin},{fout})"
        if a_in == "pop" and anim_ms > 0:
            tags += f"\\fscx70\\fscy70\\t(0,{anim_ms},\\fscx100\\fscy100)"
        if a_in in ("slide-up", "slide-down") and anim_ms > 0:
            dy = slide_off if a_in == "slide-up" else -slide_off
            tags += f"\\move({_f(x)},{_f(y + dy)},{_f(x)},{_f(y)},0,{anim_ms})"
        else:
            tags += f"\\pos({_f(x)},{_f(y)})"
        return tags

    out: list[str] = []
    # layer 0: background boxes
    if style.get("backgroundEnabled") and lay.boxes:
        col = _ass_color(style.get("backgroundColor"), "#000000")
        alpha = _ass_alpha(float(style.get("backgroundOpacity", 0.7)))
        for box in lay.boxes:
            bx, by = box.x + box.w / 2, box.y + box.h / 2
            path = cl.ass_path(cl.rounded_rect_path(box, lay.radius), dx=box.x, dy=box.y)
            tags = f"{{\\an5{anim_tags(bx, by)}\\bord0\\shad0\\blur0\\1c{col}\\1a{alpha}\\p1}}"
            out.append(f"Dialogue: 0,{t0},{t1},Default,,0,0,0,,{tags}{path}{{\\p0}}")

    an = {"left": 4, "right": 6}.get(style.get("align", "center"), 5)
    fs = lay.font_px * font.ass_size_factor
    weight = int(style.get("fontWeight", 400))
    font_tags = (
        f"\\fn{font.family}\\fs{_f(fs)}\\b{weight if weight != 400 else 0}\\i{1 if style.get('italic') else 0}"
        f"\\u{1 if style.get('underline') else 0}\\fsp{_f(float(style.get('letterSpacing', 0)) * lay.scale)}\\q2"
    )
    text_op = float(style.get("textOpacity", 1.0))
    text_alpha = _ass_alpha(text_op)
    base_color = style.get("textColor", "#FFFFFF")
    active_color = style.get("activeWordColor", "#FFD400")
    mode = style.get("wordMode", "none")
    outline = float(style.get("outlineWidth", 0)) * lay.scale if style.get("outlineEnabled") else 0.0
    windows = word_active_windows(words, end)

    def rel(t: float) -> int:
        return max(0, int(round((t - start) * 1000)))

    def line_text(idx: list[int], shadow: bool) -> str:
        parts = []
        for k, wi in enumerate(idx):
            w = words[wi]
            wcol = _ass_color(w.get("color") or base_color)
            tag = ""
            if not shadow:
                tag += f"\\1c{wcol}"
                a_s, a_e = windows[wi]
                if mode in ("highlight", "reveal-highlight"):
                    act = _ass_color(active_color)
                    tag += f"\\t({rel(a_s)},{rel(a_s) + 1},\\1c{act})\\t({rel(a_e)},{rel(a_e) + 1},\\1c{wcol})"
                elif mode == "karaoke":
                    act = _ass_color(active_color)
                    tag += f"\\t({rel(a_s)},{rel(a_s) + 1},\\1c{act})"
            if mode in ("reveal", "reveal-highlight"):
                a_s = windows[wi][0]
                vis = shadow_alpha if shadow else text_alpha
                tag += f"\\alpha&HFF&\\t({rel(a_s)},{rel(a_s) + 1},\\alpha{vis})"
            text = _escape(cl.apply_case(w["text"], style.get("textCase", "none")))
            parts.append(f"{{{tag}}}{text}" if tag else text)
            if k < len(idx) - 1:
                parts.append(" ")
        return "".join(parts)

    shadow_alpha = _ass_alpha(float(style.get("shadowOpacity", 0.6)) * text_op)
    for ln in lay.lines:
        if style.get("shadowEnabled"):
            sc = _ass_color(style.get("shadowColor"), "#000000")
            sx = ln.cx + float(style.get("shadowOffsetX", 0)) * lay.scale
            sy = ln.cy + float(style.get("shadowOffsetY", 0)) * lay.scale
            blur = float(style.get("shadowBlur", 0)) * lay.scale / 2
            tags = (f"{{\\an{an}{anim_tags(sx, sy)}{font_tags}\\bord{_f(outline)}\\shad0\\blur{_f(blur)}"
                    f"\\1c{sc}\\3c{sc}\\1a{shadow_alpha}\\3a{shadow_alpha}}}")
            out.append(f"Dialogue: 1,{t0},{t1},Default,,0,0,0,,{tags}{line_text(ln.word_indices, True)}")
        oc = _ass_color(style.get("outlineColor"), "#000000")
        tags = (f"{{\\an{an}{anim_tags(ln.cx, ln.cy)}{font_tags}\\bord{_f(outline)}\\shad0\\blur0"
                f"\\3c{oc}\\1a{text_alpha}\\3a{text_alpha}}}")
        out.append(f"Dialogue: 2,{t0},{t1},Default,,0,0,0,,{tags}{line_text(ln.word_indices, False)}")
    return out
